// Text a reader copies from a table's panel: the table as an approximate
// CREATE TABLE (a JSON schema-like document for MongoDB) or as a Markdown
// table. Pure functions of the viewer data, so they are unit-tested
// directly. Types and defaults are printed as the model recorded them: the
// model is not DDL, so the SQL says so in its first line.
//
// `table` is a node of the viewer data: { columns: [{ name, type, nullable?,
// pk?, unique?, autoIncrement?, default?, generated?, enum?, note? }],
// indexes?: [{ name?, columns, unique, where?, using? }], note? }.
// `foreignKeys`: [{ columns, to, toColumns }] for the database constraints
// (db_fk relations) held by this table.

export const SQL_HEADER = '-- Generated from the ERD; types as recorded, review before use';

const BACKTICK_ENGINES = new Set(['mysql', 'mariadb']);
// Engines with partial indexes (CREATE INDEX ... WHERE).
const PARTIAL_INDEX_ENGINES = new Set(['postgresql', 'postgres', 'sqlite']);

/** Whether `engine` gets a JSON document instead of SQL. */
export const isDocumentStore = (engine) => engine === 'mongodb';

/** Identifier quoting of `engine`: backticks for MySQL/MariaDB, else double quotes. */
export function quoter(engine) {
  if (BACKTICK_ENGINES.has(engine)) return (name) => `\`${name.replace(/`/g, '``')}\``;
  return (name) => `"${name.replace(/"/g, '""')}"`;
}

/** `schema.table` quoted, or just the table for a schemaless id (`_`). */
export function qualifiedName(id, q) {
  const [, schema, table] = id.split('.');
  return schema === '_' ? q(table) : `${q(schema)}.${q(table)}`;
}

// A default is stored as the source wrote it: an expression (now(),
// nextval(...)), a keyword or number, or a plain literal that needs quotes.
const RAW_DEFAULT = /^(-?\d+(\.\d+)?|true|false|null|current_timestamp|current_date|current_time|localtimestamp)$|\(|^'.*'$/i;
const sqlDefault = (value) => (RAW_DEFAULT.test(value) ? value : `'${value.replace(/'/g, "''")}'`);

function columnSql(c, q, engine) {
  const parts = [q(c.name), c.type];
  if (c.generated !== undefined) parts.push(`GENERATED ALWAYS AS (${c.generated}) STORED`);
  if (c.autoIncrement) parts.push(BACKTICK_ENGINES.has(engine) ? 'AUTO_INCREMENT' : engine === 'sqlite' ? '' : 'GENERATED BY DEFAULT AS IDENTITY');
  if (c.nullable === false || c.pk) parts.push('NOT NULL');
  if (c.default !== undefined) parts.push(`DEFAULT ${sqlDefault(c.default)}`);
  return parts.filter(Boolean).join(' ');
}

const tableName = (id) => id.split('.')[2];
const indexName = (id, index) => index.name ?? `${tableName(id)}_${index.columns.join('_').replace(/\./g, '_')}_${index.unique ? 'key' : 'idx'}`;

/** CREATE TABLE plus one CREATE INDEX per index, for a SQL engine. */
export function createTableSql(id, table, engine, foreignKeys = []) {
  const q = quoter(engine);
  const name = qualifiedName(id, q);
  const list = (columns) => columns.map(q).join(', ');
  const pk = table.columns.filter((c) => c.pk).map((c) => c.name);
  const lines = table.columns.map((c) => columnSql(c, q, engine));
  if (pk.length > 0) lines.push(`PRIMARY KEY (${list(pk)})`);
  for (const c of table.columns.filter((x) => x.unique && !(x.pk && pk.length === 1))) lines.push(`UNIQUE (${q(c.name)})`);
  for (const fk of foreignKeys) lines.push(`FOREIGN KEY (${list(fk.columns)}) REFERENCES ${qualifiedName(fk.to, q)} (${list(fk.toColumns)})`);
  const out = [SQL_HEADER, `CREATE TABLE ${name} (`, lines.map((l, i) => `  ${l}${i < lines.length - 1 ? ',' : ''}`).join('\n'), ');'];
  for (const index of table.indexes ?? []) {
    const mysql = BACKTICK_ENGINES.has(engine);
    const using = index.using ? (mysql ? ` USING ${index.using.toUpperCase()}` : ` USING ${index.using}`) : '';
    const head = `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${q(indexName(id, index))}`;
    const target = mysql ? `${using} ON ${name} (${list(index.columns)})` : ` ON ${name}${using} (${list(index.columns)})`;
    if (!index.where) out.push(`${head}${target};`);
    else if (PARTIAL_INDEX_ENGINES.has(engine)) out.push(`${head}${target} WHERE ${index.where};`);
    else out.push(`${head}${target}; -- partial index in the source: WHERE ${index.where}`);
  }
  return out.join('\n');
}

/**
 * A MongoDB collection as a JSON schema-like document: required fields,
 * one property per field (embedded fields under their dotted path), enum
 * values, indexes. Approximate, like the SQL.
 */
export function collectionDocument(id, table) {
  const properties = {};
  for (const c of table.columns) {
    properties[c.name] = {
      bsonType: c.type,
      ...(c.enum ? { enum: Object.keys(c.enum) } : {}),
      ...(c.default !== undefined ? { default: c.default } : {}),
      ...(c.note ? { description: c.note } : {}),
    };
  }
  const doc = {
    $comment: 'Generated from the ERD; types as recorded, review before use',
    collection: tableName(id),
    ...(table.note ? { description: table.note } : {}),
    bsonType: 'object',
    required: table.columns.filter((c) => c.nullable === false || c.pk).map((c) => c.name),
    properties,
    ...(table.indexes?.length > 0
      ? { indexes: table.indexes.map((i) => ({ ...(i.name ? { name: i.name } : {}), key: Object.fromEntries(i.columns.map((c) => [c, 1])), ...(i.unique ? { unique: true } : {}), ...(i.where ? { partialFilterExpression: i.where } : {}) })) }
      : {}),
  };
  return JSON.stringify(doc, null, 2);
}

const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** The column grid as a Markdown table, under a heading with the table name and note. */
export function markdownTable(id, table) {
  const key = (c) => [c.pk ? 'PK' : null, c.fk ? 'FK' : null, c.unique ? 'unique' : null].filter(Boolean).join(', ');
  const enumText = (c) => (c.enum ? `Values: ${Object.entries(c.enum).map(([v, m]) => (m ? `${v} (${m})` : v)).join(', ')}` : '');
  const rows = table.columns.map((c, i) =>
    [i + 1, c.name, c.type, c.nullable === true ? 'yes' : c.nullable === false ? 'no' : '', c.default ?? (c.autoIncrement ? 'auto' : ''), key(c), [c.note, enumText(c)].filter(Boolean).join(' ')].map(cell),
  );
  const head = ['#', 'Column', 'Type', 'Null', 'Default', 'Key', 'Note'];
  const lines = [`### ${tableName(id)}`, '', ...(table.note ? [table.note, ''] : []), `| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)];
  if (table.indexes?.length > 0) {
    lines.push('', '| Index | Columns | Unique | Where |', '| --- | --- | --- | --- |');
    for (const i of table.indexes) lines.push(`| ${[i.name ?? '', i.columns.join(', '), i.unique ? 'yes' : 'no', i.where ?? ''].map(cell).join(' | ')} |`);
  }
  return lines.join('\n');
}
