import assert from 'node:assert/strict';
import { test } from 'node:test';
import { buildDiagram } from '../src/layout/diagram.js';
import { viewerData } from '../src/render/svg/render.js';
import { SQL_HEADER, collectionDocument, createTableSql, isDocumentStore, markdownTable, quoter } from '../src/render/svg/viewer/schema-copy.js';
import { loadMulti } from './helpers/shop.js';

const orders = {
  note: 'One order per checkout.',
  columns: [
    { name: 'id', type: 'bigint', pk: true, autoIncrement: true, nullable: false },
    { name: 'user_id', type: 'bigint', nullable: false, fk: true, note: 'Buyer.' },
    { name: 'code', type: 'varchar(20)', unique: true },
    { name: 'status', type: 'varchar(16)', default: 'pending', enum: { pending: 'Waiting', paid: '' }, note: 'Lifecycle | state.' },
    { name: 'placed_at', type: 'timestamp', default: 'now()' },
    { name: 'total', type: 'numeric', generated: 'subtotal + tax' },
  ],
  indexes: [
    { name: 'orders_user_status', columns: ['user_id', 'status'], unique: false },
    { columns: ['code', 'status'], unique: true, where: "status = 'paid'", using: 'btree' },
  ],
};
const fks = [{ columns: ['user_id'], to: 'shop.public.users', toColumns: ['id'] }];

test('SQL for PostgreSQL: double quotes, NOT NULL, DEFAULT, keys, unique, FK and partial indexes', () => {
  assert.equal(
    createTableSql('shop.public.orders', orders, 'postgresql', fks),
    [
      SQL_HEADER,
      'CREATE TABLE "public"."orders" (',
      '  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
      '  "user_id" bigint NOT NULL,',
      '  "code" varchar(20),',
      `  "status" varchar(16) DEFAULT 'pending',`,
      '  "placed_at" timestamp DEFAULT now(),',
      '  "total" numeric GENERATED ALWAYS AS (subtotal + tax) STORED,',
      '  PRIMARY KEY ("id"),',
      '  UNIQUE ("code"),',
      '  FOREIGN KEY ("user_id") REFERENCES "public"."users" ("id")',
      ');',
      'CREATE INDEX "orders_user_status" ON "public"."orders" ("user_id", "status");',
      `CREATE UNIQUE INDEX "orders_code_status_key" ON "public"."orders" USING btree ("code", "status") WHERE status = 'paid';`,
    ].join('\n'),
  );
});

test('SQL for MySQL: backticks, AUTO_INCREMENT, USING before ON, a partial index only as a comment', () => {
  const sql = createTableSql('shop._.orders', orders, 'mysql', []);
  assert.match(sql, /^CREATE TABLE `orders` \($/m);
  assert.match(sql, /^ {2}`id` bigint AUTO_INCREMENT NOT NULL,$/m);
  assert.match(sql, /^CREATE UNIQUE INDEX `orders_code_status_key` USING BTREE ON `orders` \(`code`, `status`\); -- partial index in the source: WHERE status = 'paid'$/m);
  assert.doesNotMatch(sql, /FOREIGN KEY/, 'only database constraints become FOREIGN KEY lines');
  assert.equal(quoter('mariadb')('a`b'), '`a``b`');
  assert.equal(quoter('sqlite')('a"b'), '"a""b"');
});

test('MongoDB gets a JSON schema-like document instead of SQL', () => {
  assert.ok(isDocumentStore('mongodb') && !isDocumentStore('postgresql'));
  const doc = JSON.parse(collectionDocument('act._.events', orders));
  assert.equal(doc.collection, 'events');
  assert.deepEqual(doc.required, ['id', 'user_id']);
  assert.deepEqual(doc.properties.status, { bsonType: 'varchar(16)', enum: ['pending', 'paid'], default: 'pending', description: 'Lifecycle | state.' });
  assert.deepEqual(doc.indexes[1], { key: { code: 1, status: 1 }, unique: true, partialFilterExpression: "status = 'paid'" });
});

test('Markdown table: one row per column, pipes escaped, enum values in the note, then indexes', () => {
  const md = markdownTable('shop.public.orders', orders).split('\n');
  assert.deepEqual(md.slice(0, 6), ['### orders', '', 'One order per checkout.', '', '| # | Column | Type | Null | Default | Key | Note |', '| --- | --- | --- | --- | --- | --- | --- |']);
  assert.equal(md[6], '| 1 | id | bigint | no | auto | PK |  |');
  assert.equal(md[7], '| 2 | user_id | bigint | no |  | FK | Buyer. |');
  assert.equal(md[9], '| 4 | status | varchar(16) |  | pending |  | Lifecycle \\| state. Values: pending (Waiting), paid |');
  assert.ok(md.includes('| orders_user_status | user_id, status | no |  |'));
});

test('the generators take the viewer data as it is embedded', async () => {
  const model = await loadMulti();
  const data = viewerData(model, buildDiagram(model));
  const sql = createTableSql('auth.public.users', data.nodes['auth.public.users'], data.databases.auth.engine);
  assert.match(sql, /^CREATE UNIQUE INDEX "index_users_on_email" ON "public"\."users" \("email"\);$/m);
  assert.match(sql, /^CREATE INDEX "index_users_on_status" ON "public"\."users" USING btree \("status"\);$/m);
});
